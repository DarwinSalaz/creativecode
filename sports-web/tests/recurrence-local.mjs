import {chromium} from 'playwright-core';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const config=JSON.parse(await fs.readFile('../.local/sports-local.json','utf8'));
const base='http://127.0.0.1:5002',tenant='11111111-1111-4111-8111-111111111111';
let token;
async function api(path,method='GET',body){const r=await fetch(base+'/api/sports/v1'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});assert.equal(r.status,200,await r.clone().text());return r.status===200&&r.headers.get('content-type')?.includes('json')?r.json():null;}
token=(await api('/auth/login','POST',{tenantId:tenant,username:'admin',password:config.loginPassword})).token;
const court=crypto.randomUUID(),name='Serie UI '+Date.now();
await api('/courts','POST',{id:court,name});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},timezoneId:'America/Bogota'});
 page.setDefaultTimeout(15000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.hostname==='127.0.0.1'&&u.port==='5002'?r.continue():r.abort();});
 await page.goto(base+'/sports/index.html');
 await page.getByLabel('Negocio',{exact:true}).fill(tenant);await page.getByLabel('Usuario',{exact:true}).fill('admin');await page.getByLabel('Contraseña',{exact:true}).fill(config.loginPassword);
 await page.getByRole('button',{name:'Entrar a mi negocio'}).click();
 await page.getByRole('button',{name:/Nueva reserva/}).click();
 await page.locator('.modal select[name=court]').selectOption(court);
 await page.locator('.modal select[name=kind]').selectOption('FIXED');
 await page.getByLabel('Nombre del cliente',{exact:true}).fill(name);
 const start=new Date(Date.now()+14*86400000);start.setUTCDate(start.getUTCDate()+(2-start.getUTCDay()+7)%7);
 const date=start.toISOString().slice(0,10);
 await page.getByLabel('Inicio programado',{exact:true}).fill(date+'T21:00');
 await page.getByLabel('Fin programado',{exact:true}).fill(date+'T22:00');
 assert.equal(await page.getByLabel('Repetir hasta (opcional)').inputValue(),'');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.locator('.modal').evaluate(e=>e.scrollWidth<=e.clientWidth));
 await page.locator('.repeat-panel').scrollIntoViewIfNeeded();
 await page.screenshot({path:'../.local/recurrence-mobile.png',fullPage:true});
 let delayed=false;
 await page.route('**/api/sports/v1/reservations?**',async route=>{if(!delayed){delayed=true;await new Promise(resolve=>setTimeout(resolve,800));}await route.continue();});
 const oldWindow=page.waitForRequest(r=>r.url().includes('/api/sports/v1/reservations?'));
 await page.getByRole('button',{name:'Guardar serie semanal',exact:true}).click();
 await oldWindow;
 await page.getByText('Serie semanal guardada sin fecha de fin',{exact:true}).waitFor();
 const rules=await api('/recurrence-rules');const rule=rules.find(r=>r.courtId===court);assert.ok(rule);assert.equal(rule.untilDate,null);
 const next=new Date(date+'T12:00:00Z');next.setUTCDate(next.getUTCDate()+7);const nextDate=next.toISOString().slice(0,10);
 await page.getByLabel('Fecha de agenda').fill(nextDate);await page.getByLabel('Fecha de agenda').press('Tab');
 await page.getByLabel('Filtrar cancha').selectOption(court);
 await page.locator('.booking').filter({hasText:name}).click();
 await page.getByText('↻ Reserva de una serie semanal. Los cambios y cancelaciones aquí afectan solo esta fecha.',{exact:true}).waitFor();
 page.on('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Cancelar solo esta fecha',exact:true}).click();
 await page.getByText('Acción guardada',{exact:true}).waitFor();
 const from=nextDate+'T05:00:00Z',to=new Date(Date.parse(from)+86400000).toISOString();
 const rows=await api('/reservations?from='+encodeURIComponent(from)+'&to='+encodeURIComponent(to)+'&courtId='+court);
 assert.equal(rows.length,1);assert.equal(rows[0].status,'CANCELLED_CLIENT');
 await page.locator('.booking').filter({hasText:name}).click();
 await page.getByRole('button',{name:'Reservar este horario para otra persona',exact:true}).click();
 assert.equal(await page.getByLabel('Inicio programado').inputValue(),nextDate+'T21:00');
 assert.equal(await page.getByLabel('Nombre del cliente',{exact:true}).inputValue(),'');
 await page.getByLabel('Nombre del cliente',{exact:true}).fill('Reemplazo UI');
 await page.getByRole('button',{name:'Guardar reserva',exact:true}).click();
 await page.getByText('Reserva guardada',{exact:true}).waitFor();
 await page.getByRole('button',{name:/Administración/}).click();
 const row=page.locator('.series-row').filter({hasText:name});await row.waitFor();
 await row.getByLabel('Terminar desde').fill(date);
 await row.getByRole('button',{name:'Terminar serie',exact:true}).click();
 await page.getByText('Serie terminada desde '+date,{exact:true}).waitFor();
 assert.equal((await api('/recurrence-rules')).find(r=>r.id===rule.id).stoppedFrom,date);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log('PASS: local browser creates unbounded fixed series, shows following week, cancels only that date, permits replacement and terminates series; mobile fits.');
}finally{
 for(const r of await api('/recurrence-rules'))if(r.courtId===court)await api('/recurrence-rules/'+r.id+'/stop','POST',{fromDate:new Date().toISOString().slice(0,10),version:r.version});
 await api('/courts','POST',{id:court,name,active:false});await api('/auth/logout','POST',{});await browser.close();
}
